    public static List<DuaItem> getCategorizedDuasByTopic(String topic) {
        List<DuaItem> all = new ArrayList<>();
        all.addAll(getQuranicDuas());
        all.addAll(getSunnahDuas());
        all.addAll(getDistressDuas());

        if (topic == null || topic.isEmpty()) return all;

        List<DuaItem> filtered = new ArrayList<>();
        for (DuaItem item : all) {
            if (topic.equals(TOPIC_GUIDANCE) && (item.getTitle().contains("الهداية") || item.getTitle().contains("الثبات") || item.getTitle().contains("شرح الصدر"))) {
                filtered.add(item);
            } else if (topic.equals(TOPIC_FORGIVENESS) && (item.getTitle().contains("المغفرة") || item.getTitle().contains("التوبة") || item.getContent().contains("اغْفِرْ"))) {
                filtered.add(item);
            } else if (topic.equals(TOPIC_SUSTENANCE) && (item.getTitle().contains("الرزق") || item.getTitle().contains("خيري") || item.getTitle().contains("الدين"))) {
                filtered.add(item);
            } else if (topic.equals(TOPIC_HEALING) && (item.getTitle().contains("الشفاء") || item.getTitle().contains("العافية"))) {
                filtered.add(item);
            } else if (topic.equals(TOPIC_PARENTS) && (item.getTitle().contains("الوالدين") || item.getTitle().contains("الذرية"))) {
                filtered.add(item);
            } else if (topic.equals(TOPIC_SUCCESS) && (item.getTitle().contains("العلم") || item.getTitle().contains("القبول"))) {
                filtered.add(item);
            } else if (topic.equals(TOPIC_RELIEF) && (item.getTitle().contains("الكرب") || item.getTitle().contains("الهم") || item.getTitle().contains("الظلمات"))) {
                filtered.add(item);
            }
        }
        return filtered.isEmpty() ? all : filtered;
    }
